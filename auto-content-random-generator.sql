  FROM p,
       (VALUES ('Frontend'), ('Backend'), ('QA')) AS b(title)
  RETURNING boardid
), cols AS (
  INSERT INTO columns(title, color, boardid)
  SELECT c.title, c.color, b.boardid
  FROM boards b,
       (VALUES ('Todo',        '#ffffff'),
              ('In Progress', '#00aa00'),
              ('Review',      '#0000ff'),
              ('Done',        '#ff0000')) AS c(title, color)
