$$
DECLARE
    b  RECORD;
    todo_col  INTEGER;
    prog_col  INTEGER;
    rev_col   INTEGER;
    done_col  INTEGER;
    usr  RECORD;
    prio INTEGER;
    created_at  TIMESTAMP;
    t_id INTEGER;
BEGIN
  -- цикл по доскам
  FOR b IN SELECT boardid FROM boards LOOP
        -- получаем ID колонок для этой доски
        SELECT columnid INTO todo_col  FROM columns WHERE boardid = b.boardid AND title = 'Todo';
        SELECT columnid INTO prog_col  FROM columns WHERE boardid = b.boardid AND title = 'In Progress';
        SELECT columnid INTO rev_col   FROM columns WHERE boardid = b.boardid AND title = 'Review';
        SELECT columnid INTO done_col  FROM columns WHERE boardid = b.boardid AND title = 'Done';

        -- 100 задач
        FOR i IN 1..100 LOOP
            -- случайный исполнитель
            SELECT userid, userroleid
              INTO usr
              FROM users u
              JOIN userroles ur USING (userid)
              WHERE ur.projectid = (SELECT projectid FROM projects LIMIT 1)
              ORDER BY random()
              LIMIT 1;

            prio := (SELECT priorityid FROM priorities ORDER BY random() LIMIT 1);
            created_at := (NOW() - INTERVAL '29 days') + (random() * INTERVAL '14 days');

            INSERT INTO tasks(title, description, datecreated, dateupdated, deadline,
                              columnid, statusid, priorityid, userid, userroleid,
                              backlogid, isepic)
            VALUES (format('Task %s-%s', b.boardid, i),
                    'Generated task',
                    created_at,
                    created_at,
                    created_at + INTERVAL '21 days',
                    todo_col,             -- сначала в Todo
                    1,                    -- статус Todo
                    prio,
                    usr.userid,
                    usr.userroleid,
                    NULL,
                    false)
            RETURNING taskid INTO t_id;

           
            PERFORM pg_sleep(0);  -- микро-пауза, чтобы taskid изменился

           
            INSERT INTO columnhistories(taskid, oldcolumnid, newcolumnid, changedate)
                 VALUES (t_id, todo_col, prog_col, created_at + INTERVAL '2 days');
            INSERT INTO taskhistories (taskid, oldstatus, newstatus, changedate)
                 VALUES (t_id, 'Todo', 'In-Progress', created_at + INTERVAL '2 days');

           
            UPDATE tasks
               SET columnid = prog_col,
                   statusid = 2,
                   dateupdated = created_at + INTERVAL '2 days'
             WHERE taskid = t_id;

            INSERT INTO columnhistories(taskid, oldcolumnid, newcolumnid, changedate)
                 VALUES (t_id, prog_col, rev_col, created_at + INTERVAL '5 days');
            INSERT INTO taskhistories (taskid, oldstatus, newstatus, changedate)
                 VALUES (t_id, 'In-Progress', 'In-Progress', created_at + INTERVAL '5 days'); 

            
            UPDATE tasks
               SET columnid = rev_col,
                   statusid = 2,
                   dateupdated = created_at + INTERVAL '5 days'
             WHERE taskid = t_id;

            INSERT INTO columnhistories(taskid, oldcolumnid, newcolumnid, changedate)
                 VALUES (t_id, rev_col, done_col, created_at + INTERVAL '7 days');
            INSERT INTO taskhistories (taskid, oldstatus, newstatus, changedate)
                 VALUES (t_id, 'In-Progress', 'Complete', created_at + INTERVAL '7 days');

            UPDATE tasks
               SET columnid = done_col,
                   statusid = 3,
                   dateupdated = created_at + INTERVAL '7 days'
             WHERE taskid = t_id;
        END LOOP;
  END LOOP;
END
$$ LANGUAGE plpgsql;

